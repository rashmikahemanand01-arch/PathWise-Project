def estimate_project_cost(category, skills):
    """Return a rough optional hosting/service budget in INR.

    These are planning allowances, not quoted prices. A local prototype may
    cost ₹0; verify provider pricing and free-tier limits before deployment.
    """
    skill_names = {skill.strip().lower() for skill in skills}

    category_allowance = {
        "AI": 200,
        "Web": 150,
        "App": 150,
        "Data": 50,
        "Any": 0,
    }
    estimated_cost = category_allowance.get(category, 0)

    if "apis" in skill_names:
        estimated_cost += 300
    if "firebase" in skill_names:
        estimated_cost += 300

    return estimated_cost


def make_project(
    project_id,
    name,
    category,
    skills,
    learning,
    build,
    difficulty,
    description,
    reduced_scope,
    cost=None,
):
    if cost is None:
        cost = estimate_project_cost(category, skills)

    return {
        "id": project_id,
        "name": name,
        "category": category,
        "required_skills": skills,
        "learning_hours": learning,
        "build_hours": build,
        "cost": cost,
        "cost_note": (
            "Planning estimate for optional hosting or external services. "
            "A local prototype may cost ₹0. Verify current free-tier limits "
            "and provider pricing before deployment."
        ),
        "difficulty": difficulty,
        "description": description,
        "reduced_scope": reduced_scope,
    }


